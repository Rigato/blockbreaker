/**
 * World III — Rustwake campaign waves (phases 13-18).
 *
 * The engine under the light: slag yards, rustline depots, ash foundries,
 * boilerworks, crown stacks and finally the Sunder Core. Every grid is eight
 * columns wide and at most twelve rows tall; boss spans are left empty so the
 * centred boss never overlaps a block or a field element.
 *
 * New mechanics introduced here:
 * - `plated` (t): heavy plating, tools deal one less damage.
 * - `press` (element): vertical industrial AABB with a telegraphed slam.
 * - `belt` (element): rotates the ball's vector without changing its speed.
 * - `fused` (f): shattered circuits propagate one damage to their neighbours.
 * - `splitting` (s): breaks into up to two crystals with a generation cap.
 * - `gust` (rule): lateral wind that pushes the ball left and right.
 */

